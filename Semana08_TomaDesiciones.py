# COMPARACIÓN: OPERADORES DE IGUALDAD
print(2 == 2)
print(2 == 6)
print("si" == "si")
print(2 == 2.5)
print(2 == 2**2)
# IGUALDAD: EL OPERADOR IGUAL a (==)
a = input("Ingrese un numero:")
b = input("Escribe de nuevo tu contraseña:")
Mensaje = a == b
if Mensaje == True: 
    print("Contraseña correcta")
else:
    print("Contraseña incorrecta")

var = 0  # Asignando 0 a var
print(var == 0)
var = 1  # Asignando 1 a var
print(var == 0)

# DESIGUALDAD: EL OPERADOR NO ES IGUA a (!=)
var = 0  # Asignando 0 a var
print(var != 0)
var = 1  # Asignando 1 a var
print(var != 0)
